// Демонстрація: та сама задача (фігури з площею), що й на занятті 080,
// але через ABSTRACT CLASS замість інтерфейсу. Головна практична різниця:
// абстрактний клас може мати ГОТОВУ, СПІЛЬНУ реалізацію методу (printInfo()),
// яку успадковують усі підкласи, а не лише "контракт" без реалізації.
// area() лишається abstract - кожна фігура рахує площу по-своєму.

public abstract class AbstractShape {
    String name;

    AbstractShape(String name) {
        this.name = name;
    }

    abstract double area(); // немає тіла - кожен підклас ЗОБОВ'ЯЗАНИЙ його реалізувати

    // А цей метод - звичайний, з готовою реалізацією. Усі підкласи
    // отримають його "безкоштовно", без повторення коду в кожному з них.
    void printInfo() {
        System.out.println(name + ": площа = " + area());
    }
}
