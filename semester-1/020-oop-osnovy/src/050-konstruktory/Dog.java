// Демонстрація: конструктор - спеціальний метод, що викликається
// автоматично при "new Dog(...)" і одразу заповнює поля об'єкта.

public class Dog {
    String name;
    String breed;
    int age;

    // Конструктор має ТЕ САМЕ ім'я, що й клас, і не має типу результату.
    Dog(String name, String breed, int age) {
        // this.name - поле об'єкта; name (праворуч) - параметр конструктора.
        // this - явно вказує "поле САМЕ ЦЬОГО об'єкта", щоб не плутати
        // з однойменним параметром.
        this.name = name;
        this.breed = breed;
        this.age = age;
    }
}
