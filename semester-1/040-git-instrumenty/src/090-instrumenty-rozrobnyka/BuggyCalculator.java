// Вправа на дебагер: програма компілюється і запускається БЕЗ ПОМИЛОК,
// але видає НЕПРАВИЛЬНИЙ результат - найпідступніший тип бага, який не
// зловити простим переглядом коду, а треба покроково пройти дебагером.
//
// Очікуваний правильний результат: Сума: 429, Середній бал: 85.8
// Тут - навмисно два окремих баги. Перший знайдемо разом (керована
// практика), другий - самостійний челендж.

public class BuggyCalculator {
    public static void main(String[] args) {
        int[] grades = {80, 91, 75, 88, 95};

        int sum = 0;
        for (int i = 1; i < grades.length; i++) { // БАГ №1: має бути i = 0
            sum += grades[i];
        }

        double average = sum / grades.length; // БАГ №2: цілочисельне ділення
        System.out.println("Сума: " + sum);
        System.out.println("Середній бал: " + average);
    }
}
