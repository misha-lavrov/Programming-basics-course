// Перша програма кожного розробника. Розберемо буквально кожен рядок.

public class HelloWorld {
    // ↑ "public class HelloWorld" — оголошення класу з іменем HelloWorld.
    //   Java-правило: ім'я файлу (HelloWorld.java) МАЄ збігатися з іменем
    //   публічного класу всередині нього. Поки просто запам'ятайте це правило.

    public static void main(String[] args) {
        // ↑ Це метод main — "вхідні двері" будь-якої Java-програми.
        //   Коли ви натискаєте "Run", JVM (Java Virtual Machine) шукає саме
        //   цей метод і починає виконання коду з нього.
        //   Поки не потрібно розуміти кожне слово (public, static, void,
        //   String[] args) — до цього повернемось у блоці про методи.

        System.out.println("Hello, World!");
        // ↑ System.out.println(...) — виводить текст у консоль і переводить
        //   рядок після нього. Текст у лапках називається рядковим
        //   літералом (String) — те, що буде виведено буквально як є.
    }
}
