// Керована практика "передбач результат": перед запуском обговоріть з
// групою, яким буде виведення КОЖНОГО рядка окремо. Потім запустіть і
// звірте здогадки з реальним результатом.

public class PredictTheOutput {
    public static void main(String[] args) {
        System.out.println(17 / 5);         // ціле ділення
        System.out.println(17 % 5);         // залишок від ділення
        System.out.println(17.0 / 5);       // дробове ділення
        System.out.println(5 > 3 && 2 > 1); // логічне І (обидві умови правдиві)
        System.out.println(5 > 3 || 2 > 10);// логічне АБО (достатньо однієї)
        System.out.println(!(5 > 3));       // заперечення
        System.out.println(2 + 3 * 4);      // пріоритет: множення виконується першим
        System.out.println((2 + 3) * 4);    // дужки змінюють порядок виконання
    }
}
